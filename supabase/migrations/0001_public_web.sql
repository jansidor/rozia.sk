-- Rozia – schéma verejného webu (Supabase, región eu-central-1 Frankfurt).
-- Verejnosť číta len publikované riadky (RLS). Leady zapisuje výhradne server
-- (service role). Budúce moduly (CRM, AML, podpisy, portál) sa pripoja cez
-- agents.id / listings.id / leads.id; stĺpec org_id je pripravený na pobočky.

create extension if not exists pgcrypto;

create table agents (
  id uuid primary key default gen_random_uuid(),
  org_id uuid,
  slug text not null unique,
  name text not null,
  photo_url text,
  phone text not null check (phone ~ '^\+421 9\d{2} \d{3} \d{3}$'),
  email text,
  area text not null,
  bio text,
  sold_last_12m int,
  certification_number text,
  position int not null default 0,
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table listings (
  id bigint generated by default as identity (start with 1000) primary key,
  org_id uuid,
  slug text not null,
  title text not null,
  transaction text not null check (transaction in ('predaj', 'prenajom')),
  property_type text not null check (property_type in ('byty', 'domy', 'chaty', 'apartmany', 'pozemky')),
  city_slug text not null,
  part_slug text,
  locality_label text not null,
  price numeric(12, 2) not null check (price > 0),
  previous_price numeric(12, 2),
  area_m2 numeric(8, 2) not null check (area_m2 > 0),
  rooms int,
  floor int,
  condition text check (condition in ('povodny', 'ciastocna-rekonstrukcia', 'rekonstrukcia', 'novostavba')),
  energy_class text check (energy_class in ('A0', 'A1', 'A', 'B', 'C', 'D', 'E', 'F', 'G')), -- null = certifikát nie je
  description text,
  features text[] not null default '{}',
  status text not null default 'draft' check (status in ('draft', 'active', 'reserved', 'sold', 'archived')),
  lat double precision,
  lng double precision,
  agent_id uuid references agents (id) on delete set null,
  published_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index listings_browse on listings (status, transaction, property_type, city_slug);

create table listing_photos (
  id uuid primary key default gen_random_uuid(),
  listing_id bigint not null references listings (id) on delete cascade,
  url text not null,
  alt text not null default '',
  blur_data_url text,
  position int not null default 0
);

-- Archív predaných. Bez client_consent sa riadok verejne nikdy nezobrazí.
create table sales (
  id bigint generated by default as identity primary key,
  org_id uuid,
  listing_id bigint references listings (id) on delete set null,
  title text not null,
  property_type text not null,
  city_slug text not null,
  part_slug text,
  locality_label text not null,
  area_m2 numeric(8, 2),
  rooms int,
  price_per_m2 numeric(10, 2), -- interné, do ocenenia; verejne sa nezobrazuje
  days_on_market int not null check (days_on_market >= 0),
  pct_of_asking_price numeric(5, 2) not null,
  sold_at date not null,
  photo_url text,
  client_consent boolean not null default false,
  client_consent_at timestamptz
);

-- Cenová mapa: medián €/m² za lokalitu a štvrťrok ('2026-Q4').
create table price_stats (
  id bigint generated by default as identity primary key,
  city_slug text not null,
  part_slug text,
  rooms int,
  condition text,
  median_per_m2 numeric(10, 2) not null,
  sample_size int not null check (sample_size > 0),
  period text not null check (period ~ '^\d{4}-Q[1-4]$'),
  updated_at timestamptz not null default now()
);

create table locality_info (
  id bigint generated by default as identity primary key,
  city_slug text not null,
  part_slug text,
  schools text,
  transport text,
  parking text,
  housing text,
  agent_comment text,
  agent_id uuid references agents (id) on delete set null,
  faq jsonb not null default '[]',
  updated_at timestamptz not null default now(),
  unique nulls not distinct (city_slug, part_slug)
);

create table articles (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  excerpt text,
  body text,
  author text,
  published boolean not null default false,
  published_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Leady z formulárov. Text súhlasu sa ukladá doslovne (preukázateľnosť súhlasu).
create table leads (
  id uuid primary key default gen_random_uuid(),
  org_id uuid,
  kind text not null check (kind in ('ocenenie', 'kontakt', 'kariera', 'dopyt')),
  name text not null,
  phone text,
  email text,
  message text,
  payload jsonb not null default '{}',
  gdpr_consent boolean not null,
  gdpr_consent_text text not null,
  marketing_consent boolean not null default false,
  source_path text,
  user_agent text,
  created_at timestamptz not null default now()
);

-- Porovnateľné byty pre rýchly odhad: predaje za 12 mes. + aktívne ponuky.
-- Beží s právami vlastníka, vystavuje len €/m² a lokalitu (žiadne osobné údaje).
create view comparables as
  select city_slug, part_slug, property_type, price_per_m2, 'sale'::text as source
    from sales
   where price_per_m2 is not null and sold_at > current_date - interval '12 months'
  union all
  select city_slug, part_slug, property_type, round(price / area_m2, 2), 'listing'::text
    from listings
   where status = 'active' and transaction = 'predaj';

alter table agents enable row level security;
alter table listings enable row level security;
alter table listing_photos enable row level security;
alter table sales enable row level security;
alter table price_stats enable row level security;
alter table locality_info enable row level security;
alter table articles enable row level security;
alter table leads enable row level security; -- žiadna policy = len service role

create policy "public read" on agents for select using (published);
create policy "public read" on listings for select using (status in ('active', 'reserved', 'sold'));
create policy "public read" on listing_photos for select using (
  exists (select 1 from listings l where l.id = listing_id and l.status in ('active', 'reserved', 'sold')));
create policy "public read with consent" on sales for select using (client_consent);
create policy "public read" on price_stats for select using (true);
create policy "public read" on locality_info for select using (true);
create policy "public read" on articles for select using (published);

grant select on comparables to anon;
